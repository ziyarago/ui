#!/usr/bin/env node
// Builds dist/: one self-contained style.css (imports inlined, font URLs rewritten) and tokens.css.
// No dependencies. Run: npm run build
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = p => readFileSync(join(root, p), 'utf8');
const remote = [];

const inline = (file) => read(file).replace(/@import\s+(?:url\()?['"]([^'"]+)['"]\)?\s*;?/g, (m, ref) => {
  if (/^https?:/.test(ref)) { remote.push(m.trim().endsWith(';') ? m.trim() : m.trim() + ';'); return ''; }
  return `\n/* ${ref} */\n` + inline(join(dirname(file), ref).replace(/\\/g, '/'));
});

let css = inline('src/styles/index.css').replace(/url\((['"]?)\.\.\/\.\.\/assets\//g, 'url($1../assets/')
  // Vite inlines assets under 4 KB as data: URIs, which a strict CSP (font-src 'self') blocks; ?no-inline keeps the small subsets as files
  .replace(/(url\((['"]?)\.\.\/assets\/[^'")]+\.woff2)\2\)/g, '$1?no-inline$2)');
css = [...new Set(remote)].join('\n') + '\n' + css;
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/style.css'), '/* @ziyarago/ui · generated by scripts/build.mjs — do not edit */\n' + css);
writeFileSync(join(root, 'dist/tokens.css'), '/* generated */\n' + read('src/styles/tokens.css'));
console.log('dist/style.css', (css.length / 1024).toFixed(1) + ' KB');
