#!/usr/bin/env node
// Generates src/icons/builtin.js: the Lucide icons that the components themselves use, as inline SVG strings, loaded lazily
// (dynamic import) on the first icon, so no network request and no CSP problem for them. Names are found by scanning the source of this
// repo and of ../ZiyaraGo_UI_pro when present. Icons that apps pass by name and that are not in the set still come from the CDN
// or from setIconBase()/registerIcons(). Source: lucide-static (ISC license), version pinned in package.json.
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = join(root, 'node_modules/lucide-static/icons');
const have = new Set(readdirSync(iconDir).filter(f => f.endsWith('.svg')).map(f => f.slice(0, -4)));
// docs examples and metadata are scanned too: users copy them, and a strict CSP forbids the CDN fallback for names outside the set
const dirs = [join(root, 'src/core'), join(root, 'src/compat'), join(root, 'src/meta'), join(root, 'site/docs-data'), join(root, '../ZiyaraGo_UI_pro/src')].filter(existsSync);
const used = new Set();
const walk = d => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.(js|ts)$/.test(f)) for (const m of readFileSync(p, 'utf8').matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) if (have.has(m[1])) used.add(m[1]); } };
dirs.forEach(walk);
const names = [...used].sort();
const svg = n => readFileSync(join(iconDir, n + '.svg'), 'utf8').replace(/<!--[\s\S]*?-->\s*/g, '').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
mkdirSync(join(root, 'src/icons'), { recursive: true });
writeFileSync(join(root, 'src/icons/builtin.js'), `// generated by scripts/icons.mjs from lucide-static (ISC): do not edit\nexport default {\n${names.map(n => `  ${JSON.stringify(n)}: ${JSON.stringify(svg(n))},`).join('\n')}\n};\n`);
console.log(`icons: ${names.length} built in`);
