#!/usr/bin/env node
// Generates what ties the per-component definitions together, from the `export const <Name>Def = ...` declarations in src/core:
//   src/core/names.js  list of free component names (registry clash check, resolver, Nuxt module)
//   src/core/defs.js   barrel of every definition (tree-shakeable re-exports)
//   src/core/all.js    the merged `components` object (loads every definition: only the core entry's `components` export uses it)
//   types/internal.d.ts   the `export const <Name>Def` declarations between the core-index:defs markers
//   src/vue/index.js, src/react/index.js   the `export const UiName = comp('Name', NameDef)` blocks between the core-index markers
// Run by npm run build and npm run check (--check fails when a generated file is out of date instead of writing it).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const core = join(root, 'src/core');
const FIRST = ['components.js', 'components2.js', 'components3.js', 'components4.js', 'components6.js', 'components7.js', 'pages.js'];
const all = readdirSync(core).filter(f => f.endsWith('.js'));
const files = [...FIRST, ...all.filter(f => !FIRST.includes(f)).sort()].filter(f => all.includes(f));
const byFile = {};
for (const f of files) {
  const names = [...readFileSync(join(core, f), 'utf8').matchAll(/^export const (\w+)Def\b/gm)].map(m => m[1]);
  if (names.length) byFile[f] = names;
}
const names = Object.values(byFile).flat();
const dup = names.filter((n, i) => names.indexOf(n) !== i);
if (dup.length) { console.error('duplicate definitions: ' + dup.join(', ')); process.exit(1); }

const banner = '// generated by scripts/core-index.mjs: do not edit\n';
const out = {
  'src/core/names.js': `${banner}export const NAMES = [\n${names.map(n => `  '${n}',`).join('\n')}\n];\n`,
  'src/core/defs.js': banner + Object.entries(byFile).map(([f, ns]) => `export { ${ns.map(n => n + 'Def').join(', ')} } from './${f}';`).join('\n') + '\n',
  'src/core/all.js': `${banner}import '../i18n/components/index.js';
import { extras, onRegister } from './registry.js';
import { ${names.map(n => n + 'Def').join(', ')} } from './defs.js';

const merge = () => {
  const all = { ${names.map(n => `${n}: ${n}Def`).join(', ')} };
  Object.assign(all, extras);
  onRegister(defs => Object.assign(all, defs));
  return all;
};
/** Every built-in definition plus the registered ones. Importing this module loads all of them; the adapters only do that for install() and for plugins without \`deps\`. */
export const components = /*#__PURE__*/ merge();
`,
};
const block = (src, tag, body) => {
  const re = new RegExp(`(// <core-index:${tag}>\\n)[\\s\\S]*?(// </core-index:${tag}>)`);
  if (!re.test(src)) throw new Error('marker core-index:' + tag + ' missing');
  return src.replace(re, (_, a, b) => a + body + b);
};
for (const fw of ['vue', 'react']) {
  const p = `src/${fw}/index.js`;
  let s = readFileSync(join(root, p), 'utf8');
  s = block(s, 'imports', `import { ${names.map(n => n + 'Def').join(', ')} } from '../core/defs.js';\n`);
  s = block(s, 'exports', names.map(n => `export const Ui${n} = /*#__PURE__*/ comp('${n}', ${n}Def);\n`).join(''));
  out[p] = s;
}
{
  const p = 'types/internal.d.ts';
  out[p] = block(readFileSync(join(root, p), 'utf8'), 'defs', names.map(n => `export const ${n}Def: import('./core.js').ComponentDefinition;\n`).join(''));
}
let stale = 0;
for (const [p, body] of Object.entries(out)) {
  let cur = ''; try { cur = readFileSync(join(root, p), 'utf8'); } catch {}
  if (cur === body) continue;
  if (process.argv.includes('--check')) { console.error(`${p} is out of date: run node scripts/core-index.mjs`); stale++; } else writeFileSync(join(root, p), body);
}
console.log(`core-index: ${names.length} definitions in ${Object.keys(byFile).length} files${stale ? `, ${stale} stale` : ''}`);
if (stale) process.exit(1);
