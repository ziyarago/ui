#!/usr/bin/env node
// Generates src/i18n/components/index.js from the files in that folder and validates them:
// free files (src/i18n/components) may only hold en, ar, ru; the other 13 languages live in pro-private/i18n (gitignored, never published).
// every file must export English; other locales are optional (language packs) but must match the English keys and placeholders. Run by npm run build and npm run check.
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../src/i18n/components');
const FREE = ['en', 'ar', 'ru'];
const LOCALES = [...FREE, 'uz', 'tg', 'tr', 'fr', 'fa', 'hi', 'ur', 'bn', 'id', 'kk', 'ky', 'ms', 'ha'];
const proDir = join(dirname(fileURLToPath(import.meta.url)), '../pro-private/i18n');
const files = readdirSync(dir).filter(f => /^[A-Z][A-Za-z0-9]*\.js$/.test(f)).sort();
const names = files.map(f => f.replace(/\.js$/, ''));
writeFileSync(join(dir, 'index.js'), `// generated by scripts/i18n-index.mjs: do not edit\nimport { defineMessages } from '../index.js';\n${names.map(n => `import ${n} from './${n}.js';`).join('\n')}\n\n${names.map(n => `defineMessages('${n}', ${n});`).join('\n')}\n`);

const errors = [];
const pro = existsSync(proDir) ? readdirSync(proDir).filter(f => /^[A-Z][A-Za-z0-9]*\.js$/.test(f)) : [];
for (const f of pro) if (!names.includes(f.replace(/\.js$/, ''))) errors.push(`pro ${f}: no matching free file`);
for (const n of names) {
  const m = (await import(pathToFileURL(join(dir, n + '.js')).href)).default;
  if (!m.en) errors.push(`${n}: missing en`);
  for (const l of Object.keys(m)) if (!FREE.includes(l)) errors.push(`${n}: locale "${l}" must live in the Pro pack, not in the free package`);
  if (pro.includes(n + '.js')) { const p = (await import(pathToFileURL(join(proDir, n + '.js')).href)).default; for (const l of Object.keys(p)) { if (FREE.includes(l) || !LOCALES.includes(l)) errors.push(`pro ${n}: bad locale "${l}"`); else m[l] = p[l]; } }
  const keys = Object.keys(m.en || {});
  for (const l of LOCALES.slice(1)) {
    if (!m[l]) continue;
    for (const k of keys) if (!(k in m[l])) errors.push(`${n}.${l}: missing key "${k}"`);
    for (const k of Object.keys(m[l] || {})) if (!(k in (m.en || {}))) errors.push(`${n}.${l}: unknown key "${k}"`);
    for (const k of keys) { const a = (m.en[k].match(/\{\w+\}/g) || []).sort().join(), b = ((m[l] || {})[k]?.match(/\{\w+\}/g) || []).sort().join(); if (a !== b) errors.push(`${n}.${l}.${k}: placeholders differ (${a} vs ${b})`); }
  }
}
console.log(`i18n: ${names.length} component files, ${errors.length} errors`);
if (errors.length) { console.error(errors.slice(0, 60).join('\n')); process.exit(1); }
